'use server';

import { z } from 'zod';
import { getUser } from '@/lib/auth-utils';
import {
  confirmMemoryEntryByUser,
  deleteMemoryEntry as deleteEntry,
  getUserBio,
  getUserPreferencesByUserId,
  insertUserMemoryEntry,
  listMemoryEntries,
  saveUserBioText,
  updateMemoryEntryByUser,
} from '@/lib/db/queries';
import { MEMORY_CATEGORIES, MEMORY_LIMITS, MEMORY_TIERS, type MemoryCategory } from './constants';
import { ModelUnavailableError } from '@/ai/catalog/task-models';
import { runMemoryConsolidation } from './jobs';
import { cleanEntryText } from './ops';

async function requireUserId(): Promise<string> {
  const user = await getUser();
  if (!user) throw new Error('Authentication required');
  return user.id;
}

export interface MemoryEntryView {
  id: string;
  text: string;
  category: MemoryCategory;
  tier: 'always' | 'contextual';
  status: 'candidate' | 'confirmed';
  sensitive: boolean;
  userLocked: boolean;
  createdAt: string;
  updatedAt: string;
}

export interface MemoryOverview {
  bio: {
    userText: string;
    autoText: string;
    autoGeneratedAt: string | null;
    consolidatedAt: string | null;
  };
  entries: MemoryEntryView[];
}

export async function getMemoryOverview(): Promise<MemoryOverview> {
  const userId = await requireUserId();
  const [bio, entries] = await Promise.all([getUserBio(userId), listMemoryEntries(userId)]);
  return {
    bio: {
      userText: bio?.userText ?? '',
      autoText: bio?.autoText ?? '',
      autoGeneratedAt: bio?.autoGeneratedAt?.toISOString() ?? null,
      consolidatedAt: bio?.consolidatedAt?.toISOString() ?? null,
    },
    entries: entries.map((e) => ({
      id: e.id,
      text: e.text,
      category: e.category,
      tier: e.tier,
      status: e.status === 'candidate' ? 'candidate' : 'confirmed',
      sensitive: e.sensitive,
      userLocked: e.userLocked,
      createdAt: e.createdAt.toISOString(),
      updatedAt: e.updatedAt.toISOString(),
    })),
  };
}

const bioSchema = z.object({
  field: z.enum(['userText', 'autoText']),
  text: z.string().max(Math.max(MEMORY_LIMITS.bioUserMaxChars, MEMORY_LIMITS.bioAutoMaxChars)),
});

export async function saveMemoryBio(input: z.infer<typeof bioSchema>) {
  const userId = await requireUserId();
  const { field, text } = bioSchema.parse(input);
  const max = field === 'userText' ? MEMORY_LIMITS.bioUserMaxChars : MEMORY_LIMITS.bioAutoMaxChars;
  if (text.length > max) throw new Error(`The text must be at most ${max} characters`);
  await saveUserBioText(userId, field, text.trim(), 'user');
}

const entryTextSchema = z.string().transform((text, ctx) => {
  const cleaned = cleanEntryText(text);
  if (!cleaned) {
    ctx.addIssue({ code: 'custom', message: `Between 1 and ${MEMORY_LIMITS.entryMaxChars} characters` });
    return z.NEVER;
  }
  return cleaned;
});

const newEntrySchema = z.object({
  text: entryTextSchema,
  category: z.enum(MEMORY_CATEGORIES),
  tier: z.enum(MEMORY_TIERS),
  sensitive: z.boolean(),
});

export async function addMemoryEntry(input: z.input<typeof newEntrySchema>) {
  const userId = await requireUserId();
  const values = newEntrySchema.parse(input);
  // Typed by the user: durable by definition, and no keywords needed since
  // they can always pin it to 'always' if lexical matching misses it.
  await insertUserMemoryEntry(userId, { ...values, durability: 'permanent', keywords: [] });
}

const entryEditSchema = z.object({
  id: z.string().min(1),
  text: entryTextSchema.optional(),
  tier: z.enum(MEMORY_TIERS).optional(),
  sensitive: z.boolean().optional(),
});

export async function updateMemoryEntry(input: z.input<typeof entryEditSchema>) {
  const userId = await requireUserId();
  const { id, ...edit } = entryEditSchema.parse(input);
  const updated = await updateMemoryEntryByUser(userId, id, edit);
  if (!updated) throw new Error('Memory entry not found');
}

export async function confirmMemoryEntry(id: string) {
  const userId = await requireUserId();
  const confirmed = await confirmMemoryEntryByUser(userId, z.string().min(1).parse(id));
  if (!confirmed) throw new Error('Memory candidate not found');
}

export async function deleteMemoryEntry(id: string) {
  const userId = await requireUserId();
  await deleteEntry(userId, z.string().min(1).parse(id));
}

// Returns the configuration error as a value: a thrown one never reaches the
// browser in production.
export async function consolidateMemoryNow(): Promise<{ started: boolean; error?: string }> {
  const userId = await requireUserId();
  const record = await getUserPreferencesByUserId({ userId });
  try {
    const started = await runMemoryConsolidation(userId, record?.preferences ?? null);
    return { started };
  } catch (error) {
    if (error instanceof ModelUnavailableError) return { started: false, error: error.message };
    throw error;
  }
}
