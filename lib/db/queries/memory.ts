import 'server-only';

import { and, desc, eq, inArray, lt, ne, sql } from 'drizzle-orm';
import { memoryEntry, userBio, type MemoryEntry, type UserBio } from '../schema';
import { maindb } from '../index';
import { findDuplicate, type MemoryMutation, type NewEntryValues, type PlannableEntry } from '@/lib/memory/ops';
import type { MemoryDurability, MemoryTier } from '@/lib/memory/constants';

type Transaction = Parameters<Parameters<typeof maindb.transaction>[0]>[0];

// Serializes every memory write of one user, so a turn update, a manual edit
// and a consolidation never interleave their read-plan-write cycles.
async function lockUserMemory(tx: Transaction, userId: string) {
  await tx.execute(sql`select pg_advisory_xact_lock(hashtext(${`memory:${userId}`}))`);
}

export async function getUserBio(userId: string): Promise<UserBio | null> {
  const [bio] = await maindb.select().from(userBio).where(eq(userBio.userId, userId)).limit(1);
  return bio ?? null;
}

export async function saveUserBioText(
  userId: string,
  field: 'userText' | 'autoText',
  text: string,
  editedBy: 'user' | 'consolidation',
) {
  const now = new Date();
  const values =
    field === 'userText'
      ? { userText: text }
      : editedBy === 'user'
        ? { autoText: text, autoEditedByUserAt: now }
        : // A fresh generation already folds in the user's edits, so the next
          // one can start from it like any other generated text.
          { autoText: text, autoGeneratedAt: now, autoEditedByUserAt: null };

  await maindb
    .insert(userBio)
    .values({ userId, ...values, updatedAt: now })
    .onConflictDoUpdate({ target: userBio.userId, set: { ...values, updatedAt: now } });
}

export async function markMemoryConsolidated(userId: string) {
  const now = new Date();
  await maindb
    .insert(userBio)
    .values({ userId, consolidatedAt: now })
    .onConflictDoUpdate({ target: userBio.userId, set: { consolidatedAt: now } });
}

export async function listMemoryEntries(userId: string, { includeArchived = false } = {}): Promise<MemoryEntry[]> {
  return maindb
    .select()
    .from(memoryEntry)
    .where(
      includeArchived
        ? eq(memoryEntry.userId, userId)
        : and(eq(memoryEntry.userId, userId), ne(memoryEntry.status, 'archived')),
    )
    .orderBy(desc(memoryEntry.updatedAt));
}

export async function touchMemoryEntries(ids: string[]) {
  if (ids.length === 0) return;
  await maindb.update(memoryEntry).set({ lastUsedAt: new Date() }).where(inArray(memoryEntry.id, ids));
}

// Manual add from Settings: confirmed straight away and locked against
// model changes, since the user wrote it.
export async function insertUserMemoryEntry(
  userId: string,
  values: NewEntryValues & { sensitive: boolean },
): Promise<MemoryEntry> {
  const [entry] = await maindb
    .insert(memoryEntry)
    .values({ userId, ...values, status: 'confirmed', userLocked: true })
    .returning();
  return entry;
}

// An explicit "remember this" from the chat model. Re-stating a fact that is
// already stored confirms the existing entry instead of adding a copy.
export async function rememberMemoryEntry(
  userId: string,
  values: NewEntryValues,
  sourceChatId: string | null,
): Promise<MemoryEntry> {
  return maindb.transaction(async (tx) => {
    await lockUserMemory(tx, userId);
    const active = await tx
      .select()
      .from(memoryEntry)
      .where(and(eq(memoryEntry.userId, userId), ne(memoryEntry.status, 'archived')));

    const duplicate = findDuplicate(active, values.text);
    if (duplicate) {
      if (duplicate.status === 'confirmed') return duplicate;
      const [confirmed] = await tx
        .update(memoryEntry)
        .set({ status: 'confirmed', updatedAt: new Date() })
        .where(eq(memoryEntry.id, duplicate.id))
        .returning();
      return confirmed;
    }

    const [entry] = await tx
      .insert(memoryEntry)
      .values({ userId, ...values, status: 'confirmed', sourceChatId })
      .returning();
    return entry;
  });
}

export interface UserMemoryEntryEdit {
  text?: string;
  tier?: MemoryTier;
  sensitive?: boolean;
  keywords?: string[];
}

// Any user edit also confirms the entry and locks it against model changes.
export async function updateMemoryEntryByUser(userId: string, id: string, edit: UserMemoryEntryEdit) {
  const [entry] = await maindb
    .update(memoryEntry)
    .set({ ...edit, status: 'confirmed', userLocked: true, updatedAt: new Date() })
    .where(and(eq(memoryEntry.id, id), eq(memoryEntry.userId, userId)))
    .returning();
  return entry ?? null;
}

export async function deleteMemoryEntry(userId: string, id: string) {
  await maindb.delete(memoryEntry).where(and(eq(memoryEntry.id, id), eq(memoryEntry.userId, userId)));
}

function applyMutation(tx: Transaction, userId: string, chatId: string | null, mutation: MemoryMutation, now: Date) {
  const own = (id: string) => and(eq(memoryEntry.id, id), eq(memoryEntry.userId, userId));
  switch (mutation.kind) {
    case 'insert':
      return tx
        .insert(memoryEntry)
        .values({
          userId,
          ...mutation.values,
          status: 'candidate',
          sourceChatId: chatId,
          createdAt: now,
          updatedAt: now,
        });
    case 'update':
      return tx
        .update(memoryEntry)
        .set({ ...mutation.values, updatedAt: now })
        .where(own(mutation.id));
    case 'confirm':
      return tx.update(memoryEntry).set({ status: 'confirmed', updatedAt: now }).where(own(mutation.id));
    case 'archive':
      return tx.update(memoryEntry).set({ status: 'archived', updatedAt: now }).where(own(mutation.id));
  }
}

/**
 * Reads the user's current entries, lets `plan` decide what to change, and
 * applies the result — all under the user's memory lock, so the plan is
 * computed against exactly the rows it modifies.
 */
export async function applyMemoryMutations(
  userId: string,
  chatId: string | null,
  plan: (entries: PlannableEntry[]) => MemoryMutation[],
): Promise<MemoryMutation[]> {
  return maindb.transaction(async (tx) => {
    await lockUserMemory(tx, userId);
    const entries = await tx
      .select({
        id: memoryEntry.id,
        text: memoryEntry.text,
        status: memoryEntry.status,
        userLocked: memoryEntry.userLocked,
        sourceChatId: memoryEntry.sourceChatId,
      })
      .from(memoryEntry)
      .where(and(eq(memoryEntry.userId, userId), ne(memoryEntry.status, 'archived')));

    const mutations = plan(entries);
    const now = new Date();
    for (const mutation of mutations) await applyMutation(tx, userId, chatId, mutation, now);
    return mutations;
  });
}

export interface ConsolidatedEntry {
  id: string;
  text: string;
  tier: MemoryTier;
  keywords: string[];
}

// Applies a consolidation result: rewritten entries are updated in place and
// merged-away duplicates deleted. User-locked entries are never touched.
export async function applyMemoryConsolidation(
  userId: string,
  { updates, deleteIds }: { updates: ConsolidatedEntry[]; deleteIds: string[] },
) {
  await maindb.transaction(async (tx) => {
    await lockUserMemory(tx, userId);
    const now = new Date();
    const unlockedOwn = (id: string) =>
      and(eq(memoryEntry.id, id), eq(memoryEntry.userId, userId), eq(memoryEntry.userLocked, false));
    for (const { id, ...values } of updates) {
      await tx
        .update(memoryEntry)
        .set({ ...values, updatedAt: now })
        .where(unlockedOwn(id));
    }
    if (deleteIds.length > 0) {
      await tx
        .delete(memoryEntry)
        .where(
          and(eq(memoryEntry.userId, userId), eq(memoryEntry.userLocked, false), inArray(memoryEntry.id, deleteIds)),
        );
    }
  });
}

// Deterministic cleanup, no model involved: drop candidates that were never
// confirmed in time, and archive contextual entries unused for longer than
// their durability allows (the last use or, if never used, the last update
// counts). 'always' entries are injected on every message, so "unused" means
// nothing for them — the turn update archives them when they stop being true.
export async function expireMemoryEntries(
  userId: string,
  {
    candidateCutoff,
    unusedCutoffs,
  }: { candidateCutoff: Date; unusedCutoffs: { durability: MemoryDurability; cutoff: Date }[] },
) {
  await maindb.transaction(async (tx) => {
    await lockUserMemory(tx, userId);
    await tx
      .delete(memoryEntry)
      .where(
        and(
          eq(memoryEntry.userId, userId),
          eq(memoryEntry.status, 'candidate'),
          lt(memoryEntry.createdAt, candidateCutoff),
        ),
      );
    for (const { durability, cutoff } of unusedCutoffs) {
      await tx
        .update(memoryEntry)
        .set({ status: 'archived', updatedAt: new Date() })
        .where(
          and(
            eq(memoryEntry.userId, userId),
            eq(memoryEntry.status, 'confirmed'),
            eq(memoryEntry.tier, 'contextual'),
            eq(memoryEntry.userLocked, false),
            eq(memoryEntry.durability, durability),
            lt(sql`coalesce(${memoryEntry.lastUsedAt}, ${memoryEntry.updatedAt})`, cutoff),
          ),
        );
    }
  });
}
