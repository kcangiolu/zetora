'use client';

import { useMemo, useState } from 'react';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { sileo } from 'sileo';
import {
  PencilIcon,
  PlusIcon,
  PushPinIcon,
  PushPinSlashIcon,
  TrashIcon,
  EyeSlashIcon,
  EyeIcon,
} from '@phosphor-icons/react';
import { Check, Loader2, Sparkles, X } from 'lucide-react';

import { Button } from '@/components/ui/button';
import { Switch } from '@/components/ui/switch';
import { Textarea } from '@/components/ui/textarea';
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select';
import { HugeiconsIcon } from '@/components/ui/hugeicons';
import { Brain02Icon } from '@hugeicons/core-free-icons';
import { useSyncedPreferences } from '@/hooks/use-synced-preferences';
import {
  addMemoryEntry,
  consolidateMemoryNow,
  deleteMemoryEntry,
  getMemoryOverview,
  saveMemoryBio,
  updateMemoryEntry,
  type MemoryEntryView,
} from '@/lib/memory/actions';
import { MEMORY_CATEGORIES, MEMORY_LIMITS, type MemoryCategory } from '@/lib/memory/constants';
import { cn } from '@/lib/utils';

const MEMORY_QUERY_KEY = ['memory-overview'];
const RECENT_DAYS = 7;

const CATEGORY_LABELS: Record<MemoryCategory, string> = {
  identity: 'Identity',
  work: 'Work',
  preference: 'Preferences',
  project: 'Projects',
  skill: 'Skills',
  environment: 'Environment & tools',
  people: 'People',
};

type EntryFilter = 'all' | 'recent' | 'candidates';

function formatDate(iso: string) {
  return new Intl.DateTimeFormat('en-US', { month: 'short', day: 'numeric' }).format(new Date(iso));
}

function showError(title: string) {
  sileo.error({ title, description: 'Please try again', icon: <X className="h-4 w-4" /> });
}

export function MemoriesSection() {
  const [memoryEnabled, setMemoryEnabled] = useSyncedPreferences<boolean>('zetora-memory-enabled', true);
  const { data, isLoading } = useQuery({ queryKey: MEMORY_QUERY_KEY, queryFn: () => getMemoryOverview() });

  return (
    <div className="space-y-6">
      <div className="flex items-center justify-between gap-6">
        <div className="min-w-0">
          <p className="text-sm font-medium">Use memory in chats</p>
          <p className="text-xs text-muted-foreground mt-0.5">
            Your profile and remembered facts are given to the AI, and new facts are learned from your chats. Temporary
            chats never use memory.
          </p>
        </div>
        <Switch checked={memoryEnabled} onCheckedChange={setMemoryEnabled} />
      </div>

      <div className={cn('space-y-6', !memoryEnabled && 'opacity-50')}>
        {isLoading || !data ? (
          <div className="flex justify-center items-center h-32">
            <Loader2 className="h-4 w-4 animate-spin" />
          </div>
        ) : (
          <>
            <BioSection bio={data.bio} />
            <EntriesSection entries={data.entries} consolidatedAt={data.bio.consolidatedAt} />
          </>
        )}
      </div>
    </div>
  );
}

function BioSection({ bio }: { bio: { userText: string; autoText: string; autoGeneratedAt: string | null } }) {
  return (
    <div className="space-y-4">
      <BioField
        field="userText"
        label="About you"
        description="Written by you, never changed automatically. Who you are, what you do, what the AI should know."
        placeholder="e.g. I'm a nurse in Lyon, I self-host my services at home and I'm learning Rust."
        initialText={bio.userText}
        maxChars={MEMORY_LIMITS.bioUserMaxChars}
      />
      <BioField
        field="autoText"
        label="Learned from your chats"
        description={
          bio.autoGeneratedAt
            ? `Updated automatically (last on ${formatDate(bio.autoGeneratedAt)}). Your edits are kept as the base for the next update.`
            : 'Written automatically once there are enough remembered facts. You can edit it.'
        }
        placeholder="Nothing learned yet."
        initialText={bio.autoText}
        maxChars={MEMORY_LIMITS.bioAutoMaxChars}
      />
    </div>
  );
}

function BioField({
  field,
  label,
  description,
  placeholder,
  initialText,
  maxChars,
}: {
  field: 'userText' | 'autoText';
  label: string;
  description: string;
  placeholder: string;
  initialText: string;
  maxChars: number;
}) {
  const queryClient = useQueryClient();
  // null while unedited, so a refreshed initialText (e.g. after a tidy-up)
  // shows up instead of a stale copy.
  const [draft, setDraft] = useState<string | null>(null);
  const text = draft ?? initialText;

  const save = useMutation({
    mutationFn: () => saveMemoryBio({ field, text }),
    onSuccess: () => {
      setDraft(null);
      queryClient.invalidateQueries({ queryKey: MEMORY_QUERY_KEY });
      sileo.success({ title: 'Saved', icon: <Check className="h-4 w-4" /> });
    },
    onError: () => showError('Failed to save'),
  });

  const dirty = text.trim() !== initialText.trim();

  return (
    <div className="space-y-2">
      <div>
        <p className="text-sm font-medium">{label}</p>
        <p className="text-xs text-muted-foreground mt-0.5">{description}</p>
      </div>
      <Textarea
        value={text}
        onChange={(e) => setDraft(e.target.value)}
        placeholder={placeholder}
        maxLength={maxChars}
        className="text-[13px] min-h-24"
        disabled={save.isPending}
      />
      <div className="flex items-center justify-between">
        <span className="text-[11px] text-muted-foreground/60 tabular-nums">
          {text.length}/{maxChars}
        </span>
        {dirty && (
          <div className="flex items-center gap-2">
            <Button variant="ghost" size="sm" className="h-7 text-xs" onClick={() => setDraft(null)}>
              Cancel
            </Button>
            <Button size="sm" className="h-7 text-xs" onClick={() => save.mutate()} disabled={save.isPending}>
              {save.isPending ? <Loader2 className="h-3 w-3 animate-spin" /> : 'Save'}
            </Button>
          </div>
        )}
      </div>
    </div>
  );
}

function EntriesSection({ entries, consolidatedAt }: { entries: MemoryEntryView[]; consolidatedAt: string | null }) {
  const queryClient = useQueryClient();
  const [filter, setFilter] = useState<EntryFilter>('all');
  const [isAdding, setIsAdding] = useState(false);
  const [recentCutoff] = useState(() => Date.now() - RECENT_DAYS * 24 * 60 * 60 * 1000);

  const consolidate = useMutation({
    mutationFn: () => consolidateMemoryNow(),
    onSuccess: ({ started, error }) => {
      if (error) {
        sileo.error({ title: 'Cannot tidy up memory', description: error, icon: <X className="h-4 w-4" /> });
        return;
      }
      queryClient.invalidateQueries({ queryKey: MEMORY_QUERY_KEY });
      if (started) sileo.success({ title: 'Memory tidied up', icon: <Check className="h-4 w-4" /> });
      else sileo.info({ title: 'Already running', description: 'A tidy-up is already in progress' });
    },
    onError: () => showError('Failed to tidy up memory'),
  });

  const visible = useMemo(
    () =>
      entries.filter((e) =>
        filter === 'candidates'
          ? e.status === 'candidate'
          : filter === 'recent'
            ? new Date(e.createdAt).getTime() >= recentCutoff
            : true,
      ),
    [entries, filter, recentCutoff],
  );

  const groups = MEMORY_CATEGORIES.map((category) => ({
    category,
    entries: visible.filter((e) => e.category === category),
  })).filter((g) => g.entries.length > 0);

  const candidateCount = entries.filter((e) => e.status === 'candidate').length;

  return (
    <div className="space-y-3">
      <div className="flex items-start justify-between gap-4">
        <div className="min-w-0">
          <p className="text-sm font-medium">Remembered facts</p>
          <p className="text-xs text-muted-foreground mt-0.5">
            New facts start as candidates and are only used once they come up again in another chat.
            {consolidatedAt && ` Last tidy-up: ${formatDate(consolidatedAt)}.`}
          </p>
        </div>
        <div className="flex items-center gap-1.5 shrink-0">
          <Button
            variant="outline"
            size="sm"
            className="h-7 gap-1.5 text-xs"
            onClick={() => consolidate.mutate()}
            disabled={consolidate.isPending || entries.length === 0}
            title="Merge duplicates, clean up wording and refresh the learned profile"
          >
            {consolidate.isPending ? <Loader2 className="h-3 w-3 animate-spin" /> : <Sparkles className="h-3 w-3" />}
            Tidy up
          </Button>
          {!isAdding && (
            <Button variant="outline" size="sm" className="h-7 gap-1.5 text-xs" onClick={() => setIsAdding(true)}>
              <PlusIcon className="h-3 w-3" />
              Add
            </Button>
          )}
        </div>
      </div>

      <div className="flex items-center gap-1">
        {(
          [
            ['all', `All (${entries.length})`],
            ['recent', 'Recently added'],
            ['candidates', `Candidates (${candidateCount})`],
          ] as const
        ).map(([value, label]) => (
          <Button
            key={value}
            variant={filter === value ? 'secondary' : 'ghost'}
            size="sm"
            className="h-7 text-xs"
            onClick={() => setFilter(value)}
          >
            {label}
          </Button>
        ))}
      </div>

      {isAdding && <NewEntryForm onDone={() => setIsAdding(false)} />}

      <div className="space-y-4 max-h-[60vh] overflow-y-auto pr-1 scrollbar-w-1 scrollbar-track-transparent scrollbar-thumb-muted-foreground/20">
        {groups.length === 0 ? (
          <div className="flex flex-col justify-center items-center h-36 border border-dashed border-border/60 rounded-xl bg-muted/10">
            <div className="w-10 h-10 rounded-xl bg-muted/50 flex items-center justify-center mb-3">
              <HugeiconsIcon icon={Brain02Icon} className="h-5 w-5 text-muted-foreground" />
            </div>
            <p className="text-sm text-muted-foreground">Nothing here yet</p>
            <p className="text-[11px] text-muted-foreground/60 mt-1">Facts are learned automatically from your chats</p>
          </div>
        ) : (
          groups.map(({ category, entries: groupEntries }) => (
            <div key={category} className="space-y-1.5">
              <p className="font-pixel text-[11px] text-muted-foreground/60 uppercase tracking-wider">
                {CATEGORY_LABELS[category]}
              </p>
              {groupEntries.map((entry) => (
                <EntryRow key={entry.id} entry={entry} />
              ))}
            </div>
          ))
        )}
      </div>
    </div>
  );
}

function NewEntryForm({ onDone }: { onDone: () => void }) {
  const queryClient = useQueryClient();
  const [text, setText] = useState('');
  const [category, setCategory] = useState<MemoryCategory>('preference');

  const add = useMutation({
    mutationFn: () => addMemoryEntry({ text, category, tier: 'contextual', sensitive: false }),
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: MEMORY_QUERY_KEY });
      sileo.success({ title: 'Memory added', icon: <Check className="h-4 w-4" /> });
      onDone();
    },
    onError: () => showError('Failed to add memory'),
  });

  return (
    <div className="p-3.5 rounded-xl border border-border/60 bg-card/30 space-y-2.5">
      <Textarea
        autoFocus
        placeholder="A short fact about you, e.g. 'Prefers metric units'"
        value={text}
        onChange={(e) => setText(e.target.value)}
        maxLength={MEMORY_LIMITS.entryMaxChars}
        className="text-[13px] min-h-16"
        disabled={add.isPending}
      />
      <div className="flex items-center justify-between gap-2">
        <Select value={category} onValueChange={(value) => setCategory(value as MemoryCategory)}>
          <SelectTrigger className="h-7 w-44 text-xs">
            <SelectValue />
          </SelectTrigger>
          <SelectContent>
            {MEMORY_CATEGORIES.map((c) => (
              <SelectItem key={c} value={c} className="text-xs">
                {CATEGORY_LABELS[c]}
              </SelectItem>
            ))}
          </SelectContent>
        </Select>
        <div className="flex items-center gap-2">
          <Button variant="ghost" size="sm" className="h-7 text-xs" onClick={onDone}>
            Cancel
          </Button>
          <Button
            size="sm"
            className="h-7 text-xs"
            onClick={() => add.mutate()}
            disabled={!text.trim() || add.isPending}
          >
            {add.isPending ? <Loader2 className="h-3 w-3 animate-spin" /> : 'Save'}
          </Button>
        </div>
      </div>
    </div>
  );
}

function EntryRow({ entry }: { entry: MemoryEntryView }) {
  const queryClient = useQueryClient();
  const [isEditing, setIsEditing] = useState(false);
  const [text, setText] = useState(entry.text);

  const onSettled = () => queryClient.invalidateQueries({ queryKey: MEMORY_QUERY_KEY });
  const update = useMutation({
    mutationFn: updateMemoryEntry,
    onSuccess: () => setIsEditing(false),
    onError: () => showError('Failed to update memory'),
    onSettled,
  });
  const remove = useMutation({
    mutationFn: () => deleteMemoryEntry(entry.id),
    onError: () => showError('Failed to delete memory'),
    onSettled,
  });

  if (isEditing) {
    return (
      <div className="p-3 rounded-xl border border-border/60 bg-card/30 space-y-2">
        <Textarea
          autoFocus
          value={text}
          onChange={(e) => setText(e.target.value)}
          maxLength={MEMORY_LIMITS.entryMaxChars}
          className="text-[13px] min-h-16"
          disabled={update.isPending}
        />
        <div className="flex items-center justify-end gap-2">
          <Button
            variant="ghost"
            size="sm"
            className="h-7 text-xs"
            onClick={() => {
              setText(entry.text);
              setIsEditing(false);
            }}
          >
            Cancel
          </Button>
          <Button
            size="sm"
            className="h-7 text-xs"
            onClick={() => update.mutate({ id: entry.id, text })}
            disabled={!text.trim() || update.isPending}
          >
            {update.isPending ? <Loader2 className="h-3 w-3 animate-spin" /> : 'Save'}
          </Button>
        </div>
      </div>
    );
  }

  const isAlways = entry.tier === 'always';

  return (
    <div className="group flex items-start gap-3 px-3 py-2.5 rounded-xl border border-border/60 bg-card/30 hover:bg-card/60 transition-colors">
      <div className="flex-1 min-w-0">
        <p className={cn('text-[13px] leading-relaxed', entry.status === 'candidate' && 'text-muted-foreground')}>
          {entry.text}
        </p>
        <div className="flex flex-wrap items-center gap-2 mt-1.5 text-[10px] text-muted-foreground">
          <span>{formatDate(entry.createdAt)}</span>
          {isAlways && <span className="text-primary">Always used</span>}
          {entry.status === 'candidate' && <span className="text-amber-600 dark:text-amber-400">Candidate</span>}
          {entry.sensitive && <span className="text-destructive">Sensitive — never sent to the AI</span>}
          {entry.userLocked && <span>Edited by you</span>}
        </div>
      </div>
      <div className="flex items-center gap-0.5 shrink-0">
        <Button
          variant="ghost"
          size="icon"
          className="h-6 w-6 text-muted-foreground hover:text-foreground"
          title={isAlways ? 'Only use when relevant' : 'Always use'}
          onClick={() => update.mutate({ id: entry.id, tier: isAlways ? 'contextual' : 'always' })}
          disabled={update.isPending}
        >
          {isAlways ? <PushPinSlashIcon className="h-3 w-3" /> : <PushPinIcon className="h-3 w-3" />}
        </Button>
        <Button
          variant="ghost"
          size="icon"
          className="h-6 w-6 text-muted-foreground hover:text-foreground"
          title={entry.sensitive ? 'Allow sending to the AI' : 'Mark as sensitive (never sent to the AI)'}
          onClick={() => update.mutate({ id: entry.id, sensitive: !entry.sensitive })}
          disabled={update.isPending}
        >
          {entry.sensitive ? <EyeIcon className="h-3 w-3" /> : <EyeSlashIcon className="h-3 w-3" />}
        </Button>
        <Button
          variant="ghost"
          size="icon"
          className="h-6 w-6 text-muted-foreground hover:text-foreground"
          title="Edit"
          onClick={() => setIsEditing(true)}
        >
          <PencilIcon className="h-3 w-3" />
        </Button>
        <Button
          variant="ghost"
          size="icon"
          className="h-6 w-6 text-muted-foreground hover:text-destructive"
          title="Delete"
          onClick={() => remove.mutate()}
          disabled={remove.isPending}
        >
          {remove.isPending ? <Loader2 className="h-3 w-3 animate-spin" /> : <TrashIcon className="h-3 w-3" />}
        </Button>
      </div>
    </div>
  );
}
